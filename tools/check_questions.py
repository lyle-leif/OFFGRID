"""Run every question in tests/question_bank.json through the assistant and write a readable
report: what each question was read as (after spelling fixes), what kind of answer it got,
which guide sections were shown, and whether that is right.

    .venv\\Scripts\\python tools\\check_questions.py            # fast, guide text only
    .venv\\Scripts\\python tools\\check_questions.py --ai       # also run the AI summary (Ollama
                                                              # must be running); slow
    .venv\\Scripts\\python tools\\check_questions.py --ai --sample 40

Writes docs/question_report.md. Uses the app in-process (no server needed) with a throwaway
reports database, so nothing on the hub changes.
"""

import argparse
import json
import random
import sys
import tempfile
import time
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from fastapi.testclient import TestClient  # noqa: E402

from app import config  # noqa: E402
from app.main import app  # noqa: E402
from app.services import intents, llm  # noqa: E402

NEAR_BMC = {"lat": 13.7672, "lng": 121.0660}
STATUS_FOR_INTENT = {"nearest": "places", "nearby": "place", "distance": "route", "contact": "info", "hours": "info"}
SUMMARY_TEXT = {"verified": "AI summary kept (checked)", "dropped": "AI summary hidden (unsupported details)",
                "unavailable": "AI unavailable", "refused": "AI said not covered", "skipped": "no AI"}


def run(client, bank, group, q):
    body = {"question": q, "use_ai": True}
    if group["ctx"].get("pos"):
        body["from_pos"] = NEAR_BMC
    if group["ctx"].get("place"):
        body["location_id"] = bank["places"][group["ctx"]["place"]]
    t0 = time.perf_counter()
    events = [json.loads(x) for x in client.post("/api/assistant/ask", json=body).text.splitlines() if x.strip()]
    ms = round((time.perf_counter() - t0) * 1000)
    done = events[-1]
    norm = client.app.state.normalizer.normalize(q)
    shown = [p["chunk_id"] for e in events if e.get("type") == "passages" for p in e["passages"]]
    exp, status = group["expect"], done.get("status") or done.get("type")
    if "intent" in exp:
        got = intents.detect(norm, has_place="location_id" in body)
        answer = f"{got.kind}{' ' + got.ftype if got and got.ftype else ''}" if got else f"({status})"
        ok = bool(got) and got.kind == exp["intent"] and (not exp.get("ftype") or got.ftype == exp["ftype"]) \
            and status == STATUS_FOR_INTENT[exp["intent"]]
    elif exp.get("route"):
        answer, ok = status, status == "route"
    elif "reports" in exp:
        kinds = intents.report_query(norm, place_is_center=group["ctx"].get("place") == "bsu")
        answer = f"reports: {', '.join(kinds or [])}" if status == "reports" else status
        ok = status == "reports" and kinds == exp["reports"]
    elif "chunks" in exp:
        answer = ", ".join(shown) or status
        ok = any(s == c or (c.endswith("#") and s.startswith(c)) for s in shown for c in exp["chunks"])
    else:
        answer = "not covered" if status == "uncertain" else f"{status}: {', '.join(shown)}"
        ok = status == "uncertain"
    return {"q": q, "norm": norm, "answer": answer, "ok": ok, "ms": ms, "summary": done.get("summary"),
            "unsupported": done.get("unsupported")}


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--ai", action="store_true", help="run the real AI summary (needs Ollama)")
    ap.add_argument("--sample", type=int, default=0, help="only this many questions (random, fixed seed)")
    ap.add_argument("--out", default=str(ROOT / "docs" / "question_report.md"))
    args = ap.parse_args()

    bank = json.loads((ROOT / "tests" / "question_bank.json").read_text(encoding="utf-8"))
    cases = [(g, q) for g in bank["groups"] for q in g["qs"]]
    if args.sample:
        cases = random.Random(7).sample(cases, min(args.sample, len(cases)))

    config.REPORTS_DB = Path(tempfile.mkdtemp()) / "reports.db"
    if not args.ai:
        async def no_ai(messages):
            raise llm.LLMError("AI not used in this run")
            yield  # pragma: no cover
        llm.chat_stream = no_ai

    rows = []
    with TestClient(app) as client:
        for i, (g, q) in enumerate(cases, 1):
            rows.append((g, run(client, bank, g, q)))
            print(f"\r{i}/{len(cases)}", end="", flush=True)
    print()

    passed = sum(r["ok"] for _, r in rows)
    lines = [
        "# How the assistant reads and answers questions",
        "",
        f"Generated by `tools/check_questions.py`{' with the AI summary' if args.ai else ''}: "
        f"**{passed} of {len(rows)} questions answered the right way**.",
        "",
        "\"Read as\" is the question after spelling and text-speak fixes. Questions about places, "
        "routes and live conditions are answered from data; guide questions show the guide sections listed.",
        "",
    ]
    if args.ai:
        counts = Counter(r["summary"] for _, r in rows if r["summary"])
        lines += ["**AI summaries:** " + ", ".join(f"{SUMMARY_TEXT.get(k, k)}: {v}" for k, v in counts.most_common()), ""]
    current = None
    for g, r in rows:
        if g["name"] != current:
            current = g["name"]
            lines += ["", f"## {current}", "", "| | Question | Read as | Answer |" + (" AI |" if args.ai else ""),
                      "|---|---|---|---|" + ("---|" if args.ai else "")]
        read = "" if r["norm"] == r["q"].lower().strip() else f"`{r['norm']}`"
        ai = f" {SUMMARY_TEXT.get(r['summary'], r['summary'] or '')} |" if args.ai else ""
        lines.append(f"| {'✅' if r['ok'] else '❌'} | {r['q']} | {read} | {r['answer']} |{ai}")
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{passed}/{len(rows)} right. Report: {out}")
    return 0 if passed == len(rows) else 1


if __name__ == "__main__":
    sys.exit(main())

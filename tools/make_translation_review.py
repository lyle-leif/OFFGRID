"""Write docs/translation_review.md: every interface string in English and Tagalog, side by
side, for a native speaker to check. Fixes go into app/static/lang/tl.json only; then run
this again (and the tests, which check that both files have the same keys and {placeholders}).
    .venv\\Scripts\\python tools\\make_translation_review.py
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LANG = ROOT / "app" / "static" / "lang"
OUT = ROOT / "docs" / "translation_review.md"

# Key prefix -> section title, in the order a resident meets them.
SECTIONS = [
    ("picker", "First run: choose a language"), ("settings", "Settings"), ("app", "App name and tagline"),
    ("status", "Status pill and banners"), ("banner", "Status pill and banners"), ("theme", "Buttons on the top bar"),
    ("copy", "Offline copy line"), ("map", "Map"), ("pos", "Map buttons and messages"), ("gps", "Map buttons and messages"),
    ("report", "Map buttons and messages"), ("legend", "Map buttons and messages"), ("panel", "Panel and tabs"),
    ("tab", "Panel and tabs"), ("place", "A selected place"), ("mode", "A selected place"), ("field", "A selected place"),
    ("route", "Directions card"), ("chat", "Assistant"), ("foot", "Assistant"), ("saver", "Assistant"),
    ("chip", "Suggested questions"), ("trust", "Answer labels and notes"), ("month", "Answer labels and notes"),
    ("pr", "Answer labels and notes"), ("btn", "Answer labels and notes"), ("sum", "Answer labels and notes"),
    ("label", "Answer labels and notes"), ("err", "Errors"), ("list", "Places tab"), ("reports", "Reports tab"),
    ("rep", "Reports tab"), ("kind", "Report kinds"), ("kindshort", "Report kinds"), ("trustlabel", "Report kinds"),
    ("age", "Report kinds"), ("hotlines", "Hotlines tab"), ("type", "Place types"), ("plabel", "Place types"),
    ("ans", "The app's own answers (places, directions)"), ("loc", "The app's own answers (places, directions)"),
    ("rans", "The app's own answers (reports)"), ("road", "Route steps"), ("dir", "Route steps"), ("step", "Route steps"),
    ("rerr", "Errors"), ("apierr", "Errors"), ("setup", "Phone setup page"), ("lang", "Language name"),
]


def cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", "<br>") if text else "*(empty)*"


def main() -> int:
    en = json.loads((LANG / "en.json").read_text(encoding="utf-8"))
    tl = json.loads((LANG / "tl.json").read_text(encoding="utf-8"))
    title = dict(SECTIONS)
    order = list(dict.fromkeys(t for _, t in SECTIONS))
    groups: dict[str, list[str]] = {t: [] for t in order}
    for key in en:
        groups.setdefault(title.get(key.split(".")[0], "Other"), []).append(key)

    lines = [
        "# Tagalog translation review",
        "",
        "Every sentence the OFFGRID interface shows, in English and in Tagalog. Please check the Tagalog column: "
        "is it natural, clear in an emergency, and does it mean the same as the English?",
        "",
        "- Words in `{curly brackets}` are filled in by the app (a name, a distance, a number). Keep them, "
        "but move them wherever the Tagalog sentence needs them.",
        "- Guides and hotlines are not here: they stay in English, word for word from the official sources.",
        "- To fix a line, change it in `app/static/lang/tl.json` (same key), then run "
        "`.venv\\Scripts\\python tools\\make_translation_review.py` to refresh this page.",
        "",
        f"{len(en)} strings. Generated by `tools/make_translation_review.py`; do not edit by hand.",
        "",
    ]
    for section, keys in groups.items():
        if not keys:
            continue
        lines += [f"## {section}", "", "| Key | English | Tagalog |", "|---|---|---|"]
        lines += [f"| `{k}` | {cell(en[k])} | {cell(tl.get(k, ''))} |" for k in keys]
        lines.append("")
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {OUT} ({len(en)} strings)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
